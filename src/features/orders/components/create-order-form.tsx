import { useQueryClient } from '@tanstack/react-query'
import { useState } from 'react'
import {
  getListOrdersQueryKey,
  useCreateOrder,
} from '@/api/generated/endpoints/orders/orders'
import type { Order } from '@/api/generated/model'
import { CreateOrderBody } from '@/api/generated/zod/orders/orders.zod'
import { useAppForm } from '@/components/form'
import { FieldGroup } from '@/components/ui/field'
import { m } from '@/lib/i18n'

export function CreateOrderForm({
  onCreated,
}: {
  onCreated?: (order: Order) => void
}) {
  const queryClient = useQueryClient()
  const createOrder = useCreateOrder()
  const [serverError, setServerError] = useState<string | null>(null)

  const form = useAppForm({
    defaultValues: { customer: '', total: undefined as number | undefined },
    // Same schema the backend publishes, generated by Orval.
    validators: { onChange: CreateOrderBody },
    onSubmit: async ({ value, formApi }) => {
      setServerError(null)
      try {
        // onChange validation guarantees the shape here.
        const order = await createOrder.mutateAsync({
          data: CreateOrderBody.parse(value),
        })
        await queryClient.invalidateQueries({
          queryKey: getListOrdersQueryKey(),
        })
        formApi.reset()
        onCreated?.(order)
      } catch {
        setServerError(m.order_create_error())
      }
    },
  })

  return (
    <form
      noValidate
      onSubmit={(e) => {
        e.preventDefault()
        void form.handleSubmit()
      }}
    >
      <FieldGroup>
        <form.AppField name="customer">
          {(field) => (
            <field.TextField
              label={m.order_field_customer()}
              autoComplete="organization"
            />
          )}
        </form.AppField>
        <form.AppField name="total">
          {(field) => (
            <field.NumberField
              label={m.order_field_total()}
              description={m.order_field_total_description()}
              min={0}
              step="0.01"
            />
          )}
        </form.AppField>
        {serverError && (
          <p role="alert" className="text-destructive text-sm">
            {serverError}
          </p>
        )}
        <form.AppForm>
          <form.SubmitButton className="self-start">
            {m.order_submit()}
          </form.SubmitButton>
        </form.AppForm>
      </FieldGroup>
    </form>
  )
}
